# Build the C/C++ dependencies (FFmpeg, libass, BestSource, xxHash) from
# vcpkg.json and point Cargo at them.
#
# vcpkg's FFmpeg port refuses paths containing spaces, so the build and
# install trees live outside the repository (default: %LOCALAPPDATA%\fs-editor\deps).
param(
    [string]$Triplet = "x64-windows",
    [string]$Root = "$env:LOCALAPPDATA\fs-editor\deps"
)
$ErrorActionPreference = "Stop"
$repo = Split-Path -Parent $PSScriptRoot
if ($Root -match ' ') { throw "Dependency directory must not contain spaces: $Root" }

$vcpkg = $env:VCPKG_ROOT ? (Join-Path $env:VCPKG_ROOT "vcpkg.exe") : $null
if (-not $vcpkg -or -not (Test-Path $vcpkg)) {
    $vs = & "${env:ProgramFiles(x86)}\Microsoft Visual Studio\Installer\vswhere.exe" -latest -property installationPath
    $vcpkg = Join-Path $vs "VC\vcpkg\vcpkg.exe"
}
& $vcpkg install --triplet $Triplet `
    --x-manifest-root="$repo" `
    --x-install-root="$Root\installed" `
    --x-buildtrees-root="$Root\bt" `
    --x-packages-root="$Root\pkg"
if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }

$prefix = "$Root\installed\$Triplet".Replace('\', '/')
New-Item -ItemType Directory -Force "$repo\.cargo" | Out-Null
@"
# Generated by tools/deps.ps1 (not committed).
[env]
FS_DEPS_DIR = "$prefix"
# PCRE2 from source: a system pkg-config -L (e.g. /usr/lib) must not shadow the vcpkg FFmpeg
PCRE2_SYS_STATIC = "1"
"@ | Set-Content -Encoding utf8NoBOM "$repo\.cargo\config.toml"
Write-Host "Dependencies installed to $prefix"
