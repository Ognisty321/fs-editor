#!/bin/sh
# Build the C/C++ dependencies (FFmpeg, libass, BestSource, xxHash) from
# vcpkg.json and point Cargo at them. Needs VCPKG_ROOT (a vcpkg checkout).
set -eu
repo=$(cd "$(dirname "$0")/.." && pwd)
case "$(uname -s)" in
    Darwin) triplet=${TRIPLET:-$( [ "$(uname -m)" = arm64 ] && echo arm64-osx-dynamic || echo x64-osx-dynamic )} ;;
    *)      triplet=${TRIPLET:-x64-linux-dynamic} ;;
esac
root=${FS_DEPS_ROOT:-${XDG_CACHE_HOME:-$HOME/.cache}/fs-editor/deps}
"$VCPKG_ROOT/vcpkg" install --triplet "$triplet" \
    --x-manifest-root="$repo" \
    --x-install-root="$root/installed" \
    --x-buildtrees-root="$root/bt" \
    --x-packages-root="$root/pkg"
mkdir -p "$repo/.cargo"
# PCRE2 from source: its pkg-config would add -L/usr/lib/..., where a system FFmpeg can shadow the vcpkg one
printf '# Generated by tools/deps.sh (not committed).\n[env]\nFS_DEPS_DIR = "%s"\nPCRE2_SYS_STATIC = "1"\n' "$root/installed/$triplet" > "$repo/.cargo/config.toml"
echo "Dependencies installed to $root/installed/$triplet"
